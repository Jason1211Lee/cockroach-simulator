import assert from 'node:assert/strict';
import {createSprayAttack,stepSprayAttack,insideSprayCloud} from './spray-attack.mjs';
const a={x:0,y:0,z:0},p={x:1,y:0,z:0};
const s=createSprayAttack();
stepSprayAttack(s,.1,a,{...p,x:3});assert.equal(s.phase,'idle');
stepSprayAttack(s,.1,a,p);assert.equal(s.phase,'windup');const target={...s.target};
for(let i=0;i<7;i++)assert.equal(stepSprayAttack(s,.1,a,p).damage,false);
assert.equal(stepSprayAttack(s,.1,a,p).damage,true);assert.equal(s.phase,'cloud');
let hits=1;for(let i=0;i<30;i++)if(stepSprayAttack(s,.1,a,p).damage)hits++;
assert.equal(hits,3);assert.equal(s.phase,'recovery');
for(let i=0;i<39;i++)assert.equal(stepSprayAttack(s,.1,a,p).damage,false);
assert.equal(s.phase,'recovery');stepSprayAttack(s,.1,a,p);assert.equal(s.phase,'idle');
assert.equal(insideSprayCloud({...p,y:.8},target),true);
assert.equal(insideSprayCloud({...p,y:1.51},target),false);
assert.equal(insideSprayCloud({...p,x:2},target),false);
const fixed=createSprayAttack();stepSprayAttack(fixed,.1,a,p);
for(let i=0;i<8;i++)stepSprayAttack(fixed,.1,a,{x:4,y:0,z:4});
assert.deepEqual(fixed.target,target,'warning target does not track player');
console.log('PASS: 0.8s warning, 3s cloud, three 1s damage ticks, 4s recovery, fixed target and height/radius limits.');
